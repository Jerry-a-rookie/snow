class Dataset_HighDimTraffic(Dataset):
    """Memory-mapped high-dimensional traffic data with raw targets."""

    is_highdim_traffic = True

    def __init__(self, root_path, flag='train', size=None,
                 features='M', data_path='flow.npy',
                 target='OT', scale=True, timeenc=0, freq='15min', **kwargs):
        if size is None or len(size) < 4:
            raise ValueError('HighDimTraffic requires [seq_len, label_len, pred_len, enc_in]')
        self.seq_len = int(size[0])
        self.label_len = int(size[1])
        self.pred_len = int(size[2])
        expected_channels = [int(value) for value in size[3:6]]
        if self.label_len != 0:
            raise ValueError('HighDimTraffic requires label_len=0 for immediate forecasting')
        if features != 'M':
            raise ValueError("HighDimTraffic supports only multivariate features='M'")
        if not scale:
            raise ValueError('HighDimTraffic inputs must use training-set standardization')
        if flag not in ('train', 'val', 'test'):
            raise ValueError(f'Unsupported HighDimTraffic split: {flag}')

        self.flag = flag
        self.root_path = os.path.abspath(root_path)
        self.data_path = data_path
        self.flow_path = os.path.join(self.root_path, self.data_path)
        self.manifest_path = os.path.join(self.root_path, 'manifest.json')
        with open(self.manifest_path, 'r', encoding='utf-8') as handle:
            self.manifest = json.load(handle)

        shape = tuple(self.manifest['flow_shape'])
        if len(shape) != 2:
            raise ValueError(f'HighDimTraffic flow_shape must be [time, nodes], got {shape}')
        if any(value != shape[1] for value in expected_channels):
            raise ValueError(
                'HighDimTraffic node count must match enc_in/dec_in/c_out: '
                f"dataset={shape[1]}, configured={expected_channels}"
            )
        self.time_steps, self.n_nodes = shape
        self.mean = float(self.manifest['train_mean'])
        self.std = float(self.manifest['train_std'])
        if not np.isfinite(self.std) or self.std <= 0:
            raise ValueError(f'Invalid HighDimTraffic train_std: {self.std}')
        self.tod = int(self.manifest['time_encoding']['tod'])
        self.dow = int(self.manifest['time_encoding']['dow'])

        split = self.manifest['split']
        train_end = int(split['train_end'])
        val_end = int(split['val_end'])
        borders = {
            'train': (0, train_end),
            'val': (train_end - self.seq_len, val_end),
            'test': (val_end - self.seq_len, self.time_steps),
        }
        self.border1, self.border2 = borders[flag]
        if self.border1 < 0 or self.border2 > self.time_steps:
            raise ValueError(f'Invalid HighDimTraffic split borders: {borders[flag]}')
        self._flow = None
        flow = self._get_flow()
        if tuple(flow.shape) != shape or flow.dtype != np.dtype('float32'):
            raise ValueError(
                f'flow.npy does not match manifest: shape={flow.shape}, dtype={flow.dtype}'
            )

    def _get_flow(self):
        if self._flow is None:
            self._flow = np.load(self.flow_path, mmap_mode='r')
        return self._flow

    @staticmethod
    def _time_marks(start, end, tod, dow):
        indices = np.arange(start, end, dtype=np.int64)
        marks = np.empty((end - start, 2), dtype=np.float32)
        marks[:, 0] = indices % tod
        marks[:, 1] = (indices // tod) % dow
        return marks

    def __getitem__(self, index):
        local_start = int(index)
        x_start = self.border1 + local_start
        x_end = x_start + self.seq_len
        y_start = x_end
        y_end = y_start + self.pred_len
        flow = self._get_flow()

        seq_x = np.asarray(flow[x_start:x_end], dtype=np.float32)
        seq_x = (seq_x - self.mean) / self.std
        seq_y = np.asarray(flow[y_start:y_end], dtype=np.float32)
        seq_x_mark = self._time_marks(x_start, x_end, self.tod, self.dow)
        seq_y_mark = self._time_marks(y_start, y_end, self.tod, self.dow)
        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return self.border2 - self.border1 - self.seq_len - self.pred_len + 1

    def inverse_transform(self, data):
        return data * self.std + self.mean

    def __getstate__(self):
        state = self.__dict__.copy()
        state['_flow'] = None
        return state


class Dataset_Solar(Dataset):
    def __init__(self, root_path, flag='train', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, timeenc=0, freq='h', **kwargs):
        # size [seq_len, label_len, pred_len]
        # info
        self.seq_len = size[0]
        self.label_len = size[1]
        self.pred_len = size[2]
        # init
        assert flag in ['train', 'test', 'val']
        type_map = {'train': 0, 'val': 1, 'test': 2}
        self.set_type = type_map[flag]

        self.features = features
        self.target = target
        self.scale = scale
        self.timeenc = timeenc
        self.freq = freq

        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = StandardScaler()
        df_raw = []
        with open(os.path.join(self.root_path, self.data_path), "r", encoding='utf-8') as f:
            for line in f.readlines():
                line = line.strip('\n').split(',')
                data_line = np.stack([float(i) for i in line])
                df_raw.append(data_line)
        df_raw = np.stack(df_raw, 0)
        df_raw = pd.DataFrame(df_raw)

        num_train = int(len(df_raw) * 0.7)
        num_test = int(len(df_raw) * 0.2)
        num_valid = int(len(df_raw) * 0.1)
        border1s = [0, num_train - self.seq_len, len(df_raw) - num_test - self.seq_len]
        border2s = [num_train, num_train + num_valid, len(df_raw)]
        border1 = border1s[self.set_type]
        border2 = border2s[self.set_type]

        df_data = df_raw.values

        if self.scale:
            train_data = df_data[border1s[0]:border2s[0]]
            self.scaler.fit(train_data)
            data = self.scaler.transform(df_data)
        else:
            data = df_data

        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]

    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        seq_y = self.data_y[r_begin:r_end]
        seq_x_mark = torch.zeros((seq_x.shape[0], 1))
        seq_y_mark = torch.zeros((seq_x.shape[0], 1))

        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.data_x) - self.seq_len - self.pred_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)


class Dataset_Pred(Dataset):
    def __init__(self, root_path, flag='pred', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, inverse=False, timeenc=0, freq='15min', cols=None, **kwargs):
        # size [seq_len, label_len, pred_len]
        # info
        if size == None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        # init
        assert flag in ['pred']

        self.features = features
        self.target = target
        self.scale = scale
        self.inverse = inverse
        self.timeenc = timeenc
        self.freq = freq
        self.cols = cols
        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()

    def __read_data__(self):
        self.scaler = StandardScaler()
        df_raw = pd.read_csv(os.path.join(self.root_path,
                                          self.data_path))
        '''
        df_raw.columns: ['date', ...(other features), target feature]
        '''
        if self.cols:
            cols = self.cols.copy()
            cols.remove(self.target)
        else:
            cols = list(df_raw.columns)
            cols.remove(self.target)
            cols.remove('date')
        df_raw = df_raw[['date'] + cols + [self.target]]
        border1 = len(df_raw) - self.seq_len
        border2 = len(df_raw)

        if self.features == 'M' or self.features == 'MS':
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features == 'S':
            df_data = df_raw[[self.target]]

        if self.scale:
            self.scaler.fit(df_data.values)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values

        tmp_stamp = df_raw[['date']][border1:border2]
        tmp_stamp['date'] = pd.to_datetime(tmp_stamp.date)
        pred_dates = pd.date_range(tmp_stamp.date.values[-1], periods=self.pred_len + 1, freq=self.freq)

        df_stamp = pd.DataFrame(columns=['date'])
        df_stamp.date = list(tmp_stamp.date.values) + list(pred_dates[1:])
        if self.timeenc == 0:
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            df_stamp['minute'] = df_stamp.date.apply(lambda row: row.minute, 1)
            df_stamp['minute'] = df_stamp.minute.map(lambda x: x // 15)
            data_stamp = df_stamp.drop(['date'], 1).values
        elif self.timeenc == 1:
            data_stamp = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = data_stamp.transpose(1, 0)

        self.data_x = data[border1:border2]
        if self.inverse:
            self.data_y = df_data.values[border1:border2]
        else:
            self.data_y = data[border1:border2]
        self.data_stamp = data_stamp

    def __getitem__(self, index):
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len

        seq_x = self.data_x[s_begin:s_end]
        if self.inverse:
            seq_y = self.data_x[r_begin:r_begin + self.label_len]
        else:
            seq_y = self.data_y[r_begin:r_begin + self.label_len]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]

        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        return len(self.data_x) - self.seq_len + 1

    def inverse_transform(self, data):
        return self.scaler.inverse_transform(data)
